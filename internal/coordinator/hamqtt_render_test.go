// failingPublisher fails the test on contact. Step 4 changes no publish path
// and nothing new reaches a broker; this is the assertion of that, driven
// through every entry point the new path has.
type failingPublisher struct{ t *testing.T }

func (f failingPublisher) Publish(context.Context, string, []byte, mqtt.QoS, bool, ...mqtt.PublishOption) error {
	f.t.Errorf("the go-hamqtt rendering path published to the broker")
	return nil
}

func (f failingPublisher) Subscribe(context.Context, string, mqtt.QoS, mqtt.MessageHandler, ...mqtt.SubscribeOption) (mqtt.SubscribeResult, error) {
	f.t.Errorf("the go-hamqtt rendering path subscribed")
	return mqtt.SubscribeResult{}, nil
}

func (f failingPublisher) Unsubscribe(context.Context, string) error { return nil }

func TestHamqttRenderPathPublishesNothing(t *testing.T) {
	for _, sc := range surfaceScenarios() {
		t.Run(sc.name, func(t *testing.T) {
			in := buildHamqttInputs(t, sc)
			cfg := scenarioConfig(sc)
			d := hass.New(cfg.HASSBaseTopic, cfg.MQTTTopic, cfg.Language, failingPublisher{t: t})
			if _, err := d.RenderHamqtt(in.points, in.infos, in.climateInfos); err != nil {
				t.Fatalf("RenderHamqtt: %v", err)
			}
			if _, err := d.RenderHamqttSchedules(in.schedules, in.configURL); err != nil {
				t.Fatalf("RenderHamqttSchedules: %v", err)
			}
			if _, err := d.HamqttModel(in.points, in.infos, in.climateInfos); err != nil {
				t.Fatalf("HamqttModel: %v", err)
			}
			if _, err := d.HamqttScheduleModel(in.schedules, in.configURL); err != nil {
				t.Fatalf("HamqttScheduleModel: %v", err)
			}
		})
	}
}

// --- the legacy topic form --------------------------------------------------

// TestHamqttLegacyTopicForm settles, against the PINNED topics rather than
// against this bridge's own ConfigTopic, which publisher.LegacyTopicFunc step 6
// must state in publisher.Config.LegacyEntityTopics.
//
// It is the single fact step 6 turns on. Getting it wrong is silent and total:
// a form that retracts none of the retained per-entity configs leaves the
// device bundle refused with one WARNING line as the only evidence, and
// Config.LegacyEntityTopics REPLACES the default rather than extending it — so
// saying nothing keeps the five-segment default, which retracts nothing here.
//
// All three forms the library ships are transcribed against all 264 pinned
// topics, so the test cannot pass vacuously: one must reproduce every topic and
// the other two must reproduce none.
func TestHamqttLegacyTopicForm(t *testing.T) {
	type candidate struct {
		name string
		fn   publisher.LegacyTopicFunc
	}
	candidates := []candidate{
		{"LegacyTopicByUniqueID", publisher.LegacyTopicByUniqueID},
		{"LegacyTopicWithNodeID (the library default)", publisher.LegacyTopicWithNodeID},
		{"LegacyTopicByObjectID", publisher.LegacyTopicByObjectID},
	}
	hits := make([]int, len(candidates))
	total := 0

	for _, sc := range surfaceScenarios() {
		want := goldenConfigs(t, sc.name)
		in := buildHamqttInputs(t, sc)
		devs, err := in.disc.HamqttModel(in.points, in.infos, in.climateInfos)
		if err != nil {
			t.Fatal(err)
		}
		schedDevs, err := in.disc.HamqttScheduleModel(in.schedules, in.configURL)
		if err != nil {
			t.Fatal(err)
		}
		ctx := in.disc.HamqttContext()
		for _, hd := range append(devs, schedDevs...) {
			for _, e := range hamodel.ApplySuppression(hd.Entities) {
				comp, err := discovery.RenderComponent(ctx, hd.Device, e, discovery.Origin{})
				if err != nil {
					t.Fatal(err)
				}
				le := publisher.LegacyEntity{
					Prefix:    "homeassistant",
					Platform:  string(comp.Platform),
					NodeID:    ctx.NodeID(hd.Device),
					ObjectID:  e.Key(),
					UniqueID:  comp.UniqueID,
					Component: comp,
				}
				total++
				for i, c := range candidates {
					if _, pinned := want[c.fn(le)]; pinned {
						hits[i]++
					}
				}
			}
		}
	}

	const wantTotal = 264
	if total != wantTotal {
		t.Fatalf("examined %d components, want %d", total, wantTotal)
	}
	if hits[0] != wantTotal {
		t.Errorf("%s reproduced %d of %d pinned config topics, want all",
			candidates[0].name, hits[0], wantTotal)
	}
	for i := 1; i < len(candidates); i++ {
		if hits[i] != 0 {
			t.Errorf("%s reproduced %d of %d pinned config topics, want none — "+
				"the verdict is only safe while the forms are distinguishable",
				candidates[i].name, hits[i], wantTotal)
		}
	}
	if hass.LegacyConfigTopicForm != "publisher."+strings.Fields(candidates[0].name)[0] {
		t.Errorf("hass.LegacyConfigTopicForm = %q, but %s is the form that reproduces the pinned topics",
			hass.LegacyConfigTopicForm, candidates[0].name)
	}
}

// --- Home Assistant's own schemas -------------------------------------------

// TestHamqttValidatesAgainstHomeAssistant runs every rendered payload through
// discovery.ValidateBody — Home Assistant's own MQTT discovery schemas, as
// go-ha-catalog carries them.
//
// This is a question this bridge had never asked of its own output. It matters
// beyond hygiene because of what step 6 does with the answer: a device bundle
// is validated as ONE document, and discovery.Validate reporting it Blocking()
// means the bundle publishes NOTHING AT ALL — so a single refused component
// costs the device its entire entity set rather than one entity. Home
// Assistant's own response to a refused per-entity config today is nothing
// visible at all: the config is dropped during schema validation, before the
// entity is constructed, with no error on the wire and no log line naming the
// cause.
func TestHamqttValidatesAgainstHomeAssistant(t *testing.T) {
	checked := 0
	refusals := map[string]int{}
	for _, sc := range surfaceScenarios() {
		in := buildHamqttInputs(t, sc)
		for _, c := range renderHamqtt(t, in) {
			var body map[string]any
			if err := json.Unmarshal(c.Body, &body); err != nil {
				t.Fatal(err)
			}
			checked++
			if err := discovery.ValidateBody(hacatalog.Platform(c.Platform), body); err != nil {
				var ve *discovery.ValidationError
				if errors.As(err, &ve) && !ve.Blocking() {
					continue // advisory only
				}
				refusals[fmt.Sprintf("%s: %v", c.Platform, err)]++
			}
		}
	}
	if checked != 264 {
		t.Errorf("validated %d payloads, want 264", checked)
	}
	if len(refusals) != 0 {
		for _, k := range sortedIntKeys(refusals) {
			t.Errorf("discovery.ValidateBody refuses %d payload(s): %s", refusals[k], k)
		}
	}
}

// TestHamqttBundleValidates renders each scenario's devices as device BUNDLES —
// the form step 6 publishes — and validates each as one document.
//
// It is the same schema check at the granularity that actually bites: a
// blocking bundle publishes nothing, so a fault that costs one entity on
// today's per-entity form costs a device all of its entities on the bundle.
//
// The bundle carries an origin block and the per-entity form does not. That is
// not an inconsistency: discovery.Validate makes origin.name a blocking issue
// on a bundle and optional on a per-entity config, and F12 (adding the origin
// block to the published payloads) is deliberately NOT part of this step —
// it would be a 264-row payload addition inside the byte-equality proof.
func TestHamqttBundleValidates(t *testing.T) {
	bundles, components := 0, 0
	for _, sc := range surfaceScenarios() {
		t.Run(sc.name, func(t *testing.T) {
			in := buildHamqttInputs(t, sc)
			devs, err := in.disc.HamqttModel(in.points, in.infos, in.climateInfos)
			if err != nil {
				t.Fatal(err)
			}
			schedDevs, err := in.disc.HamqttScheduleModel(in.schedules, in.configURL)
			if err != nil {
				t.Fatal(err)
			}
			ctx := in.disc.HamqttContext()
			origin := discovery.Origin{Name: "go-daikin2mqtt"}
			for _, hd := range append(devs, schedDevs...) {
				b, err := discovery.Render(ctx, hd.Device, hd.Entities, origin)
				if err != nil {
					t.Fatalf("Render bundle for %s: %v", hd.Device.UID(), err)
				}
				bundles++
				components += len(b.Components)
				if err := discovery.Validate(b); err != nil {
					var ve *discovery.ValidationError
					if errors.As(err, &ve) && !ve.Blocking() {
						t.Logf("advisory on %s: %v", hd.Device.UID(), err)
						continue
					}
					t.Errorf("discovery.Validate refuses the bundle for %s: %v", hd.Device.UID(), err)
				}
			}
		})
	}
	t.Logf("validated %d device bundles carrying %d components", bundles, components)
}

// TestHamqttBundledClimateReadsASiblingComponentsTopic narrows — as far as it
// can be narrowed without a live Home Assistant — the one open question the
// measurement left gating step 6 (§3.4, third item).
//
// The composite climate's current_temperature_topic points at a state topic
// that belongs to ANOTHER component of the same device: room_temperature is not
// among the three entities the composite suppresses, so in a device bundle the
// two sit side by side and one reads the other's topic. Whether Home Assistant
// objects to that inside one document is a runtime question and stays one.
//
// What this settles is everything below it: the shape really does occur (it is
// not hypothetical), the library renders it without complaint, and Home
// Assistant's own discovery SCHEMAS — which is what discovery.Validate checks —
// do not refuse it. So what remains to be tested against HA 2026.9 is the
// runtime behaviour alone, on a bundle this test proves is buildable.
func TestHamqttBundledClimateReadsASiblingComponentsTopic(t *testing.T) {
	in := buildHamqttInputs(t, surfaceScenarios()[8]) // multisplit.en
	devs, err := in.disc.HamqttModel(in.points, in.infos, in.climateInfos)
	if err != nil {
		t.Fatal(err)
	}
	ctx := in.disc.HamqttContext()
	found := 0
	for _, hd := range devs {
		b, err := discovery.Render(ctx, hd.Device, hd.Entities, discovery.Origin{Name: "go-daikin2mqtt"})
		if err != nil {
			t.Fatal(err)
		}
		climate, ok := b.Components["climate"]
		if !ok {
			continue
		}
		raw, err := json.Marshal(climate)
		if err != nil {
			t.Fatal(err)
		}
		var body map[string]any
		if err := json.Unmarshal(raw, &body); err != nil {
			t.Fatal(err)
		}
		want, _ := body["current_temperature_topic"].(string)
		if want == "" {
			t.Fatalf("%s: the composite climate names no current_temperature_topic", hd.Device.UID())
		}
		sibling, ok := b.Components["room_temperature"]
		if !ok {
			t.Fatalf("%s: room_temperature is not a sibling component; the shape has changed", hd.Device.UID())
		}
		if sibling.StateTopic != want {
			t.Errorf("%s: climate reads %q, sibling publishes %q", hd.Device.UID(), want, sibling.StateTopic)
		}
		// It is a sibling, not a suppressed entity: the composite suppresses
		// power, operation_mode and the setpoint, and none of those is this.
		for _, suppressed := range []string{"power", "operation_mode", "temperature_setpoint"} {
			if _, present := b.Components[suppressed]; present {
				t.Errorf("%s: %q survived suppression", hd.Device.UID(), suppressed)
			}
		}
		if err := discovery.Validate(b); err != nil {
			t.Errorf("%s: Home Assistant's schemas refuse the bundle: %v", hd.Device.UID(), err)
		}
		found++
	}
	if found != 2 {
		t.Fatalf("found %d bundled composites on the two-indoor multi-split, want 2", found)
	}
}

// --- helpers ---------------------------------------------------------------

func sortedStringKeys(m map[string]string) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}

func sortedIntKeys(m map[string]int) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}
