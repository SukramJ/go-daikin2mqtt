// ADR 0070 phase 8 step 4 — the decisive experiment.
//
// These tests prove that go-hamqtt reproduces this bridge's published discovery
// payloads BYTE FOR BYTE, while publishing nothing.
//
// What "byte for byte" means here is what the pin itself means by it: the
// comparison is on canonical re-encoding, the same standard
// TestPublishedSurfaceGolden holds. Both sides go through encoding/json, which
// sorts object keys, so key ORDER cannot make a run pass or fail — the bridge
// marshals a struct in field order and the library marshals a map, and neither
// order is a fact Home Assistant can see. Every key, every value and every
// topic is compared exactly.
//
// The comparison runs against the GOLDEN FILES — the twelve scenarios as
// #75/#76 left them — not against the builders they guard. No golden is
// regenerated by anything in this file: -update-surface-golden is not
// reachable from here, and none of the twelve SHA-256 literals in
// goldenDigests moves.
//
// One key group is reproduced SEMANTICALLY rather than literally, named once
// here and nowhere else: the library's default path renders availability as a
// LIST and this bridge publishes the singular `availability_topic` with
// top-level payloads. Home Assistant accepts both spellings identically and an
// entity's registry keys are unaffected. hass.singularAvailability performs
// that one re-spelling, and it refuses anything that is not exactly one
// bridge-level source — so model.BridgeOnly stays load-bearing (decision F8).

// --- the inputs ------------------------------------------------------------

// hamqttInputs is one scenario's discovery inputs: exactly what
// Coordinator.pollOnce hands hass.Discovery.Publish, plus the schedule list it
// hands PublishSchedules.
type hamqttInputs struct {
	points       []process.Point
	infos        map[string]hass.DeviceInfo
	climateInfos map[string]hass.ClimateInfo
	schedules    []hass.ScheduleInfo
	configURL    string
	disc         *hass.Discovery
}

// buildHamqttInputs runs a scenario exactly as buildSurface does — the same
// coordinator, the same two poll cycles, the same real catalogue and fixtures —
// and then re-derives the discovery inputs from the warmed caches.
//
// The re-derivation is NOT taken on trust: TestHamqttInputsReproduceThePublished
// ConfigTopics feeds these very inputs back through the daemon's own builders
// and requires the result to equal the golden's config plane exactly. A
// divergence in the derivation therefore fails loudly instead of quietly
// weakening the byte-equality proof that rests on it.
func buildHamqttInputs(t *testing.T, sc surfaceScenario) hamqttInputs {
	t.Helper()

	raw, err := os.ReadFile(sc.fixture)
	if err != nil {
		t.Fatalf("read fixture: %v", err)
	}
	cat := loadRealCatalog(t)

	rec := &recorderMQTT{}
	cfg := scenarioConfig(sc)
	disc := hass.New(cfg.HASSBaseTopic, cfg.MQTTTopic, cfg.Language, rec)
	c := New(Deps{
		Cfg: cfg, Client: &stubCloud{devices: raw}, MQTT: rec, Catalog: cat,
		HASS: disc, Logger: slog.New(slog.DiscardHandler), Clock: func() time.Time { return goldenClock },
	})
	if sc.local {
		c.deps.FaikinMQTT = rec
	}
	if sc.sched != nil {
		c.AttachScheduler(&stubScheduler{doc: sc.sched})
	}

	ctx, cancel := context.WithCancel(t.Context())
	defer cancel()
	c.PublishOnline(ctx)
	c.pollOnce(ctx)
	c.pollOnce(ctx)

	devices, err := daikinmodel.ParseDevices(raw)
	if err != nil {
		t.Fatalf("parse devices: %v", err)
	}
	points := process.ResolveAt(devices, cat, goldenClock)
	if cfg.LocalEnabled() {
		points = append(points, c.localOnlyPoints(devices, points)...)
	}
	points = append(points, c.refreshPoints(devices)...)
	points = append(points, c.schedulePoints(devices)...)

	infos := deviceInfos(devices)
	c.applyFaikinConfigURLs(infos)

	in := hamqttInputs{
		points:       points,
		infos:        infos,
		climateInfos: climateInfos(devices, cfg.Language),
		configURL:    c.webConfigURL(),
		disc:         disc,
	}
	if sc.sched != nil {
		for i := range sc.sched.Schedules {
			s := &sc.sched.Schedules[i]
			in.schedules = append(in.schedules, hass.ScheduleInfo{ID: s.ID, Name: s.Name})
		}
	}
	return in
}

// --- the golden side -------------------------------------------------------

// goldenConfigs returns a scenario's discovery config plane as it is pinned on
// disk: topic -> canonical encoding of the payload. It reads the golden FILE
// and never the builders.
func goldenConfigs(t *testing.T, scenario string) map[string]string {
	t.Helper()
	doc := readGolden(t, filepath.Join("testdata", "surface", scenario+".json"))
	out := map[string]string{}
	for _, m := range doc.Messages {
		if !isConfigTopic(m.Topic) {
			continue
		}
		if m.JSON == nil {
			t.Fatalf("%s: config message %q carries no decoded payload", scenario, m.Topic)
		}
		b, err := json.Marshal(m.JSON)
		if err != nil {
			t.Fatalf("canonical encode %q: %v", m.Topic, err)
		}
		if _, dup := out[m.Topic]; dup {
			t.Fatalf("%s: golden holds %q twice", scenario, m.Topic)
		}
		out[m.Topic] = string(b)
	}
	return out
}

func isConfigTopic(topic string) bool {
	return strings.HasPrefix(topic, "homeassistant/") && strings.HasSuffix(topic, "/config")
}

// canonical re-encodes a rendered body so both sides are compared on the same
// footing: sorted keys, no formatting.
func canonical(t *testing.T, body []byte) string {
	t.Helper()
	var obj map[string]any
	if err := json.Unmarshal(body, &obj); err != nil {
		t.Fatalf("decode rendered body: %v", err)
	}
	b, err := json.Marshal(obj)
	if err != nil {
		t.Fatalf("canonical encode: %v", err)
	}
	return string(b)
}

// renderHamqtt renders a scenario's whole discovery plane through go-hamqtt.
func renderHamqtt(t *testing.T, in hamqttInputs) []hass.HamqttConfig {
	t.Helper()
	got, err := in.disc.RenderHamqtt(in.points, in.infos, in.climateInfos)
	if err != nil {
		t.Fatalf("RenderHamqtt: %v", err)
	}
	if len(in.schedules) > 0 {
		sched, err := in.disc.RenderHamqttSchedules(in.schedules, in.configURL)
		if err != nil {
			t.Fatalf("RenderHamqttSchedules: %v", err)
		}
		got = append(got, sched...)
	}
	return got
}

// --- the experiment --------------------------------------------------------

// TestHamqttReproducesPublishedConfigs is the step-4 proof: every one of the
// 264 pinned discovery payloads across the twelve scenarios, rendered by
// go-hamqtt from a model.Device, its entities' descriptions and bindings, an
// own topic.Layout and an own discovery.Context — compared key by key against
// the golden FILES.
func TestHamqttReproducesPublishedConfigs(t *testing.T) {
	total, matched := 0, 0
	for _, sc := range surfaceScenarios() {
		t.Run(sc.name, func(t *testing.T) {
			want := goldenConfigs(t, sc.name)
			in := buildHamqttInputs(t, sc)
			got := map[string]string{}
			for _, c := range renderHamqtt(t, in) {
				if _, dup := got[c.Topic]; dup {
					t.Fatalf("rendered %q twice", c.Topic)
				}
				got[c.Topic] = canonical(t, c.Body)
			}

			for _, topic := range sortedStringKeys(want) {
				total++
				g, ok := got[topic]
				if !ok {
					t.Errorf("- not rendered: %s", topic)
					continue
				}
				if g != want[topic] {
					t.Errorf("~ %s\n  golden   %s\n  rendered %s", topic, want[topic], g)
					continue
				}
				matched++
			}
			for _, topic := range sortedStringKeys(got) {
				if _, ok := want[topic]; !ok {
					t.Errorf("+ rendered a config the bridge does not publish: %s", topic)
				}
			}
			if len(want) == 0 {
				t.Fatalf("scenario %q pins no discovery config at all", sc.name)
			}
		})
	}
	// The census is a Go literal so shrinking the proof is a declaration in
	// the review rather than a quietly smaller number.
	const wantTotal = 264
	if total != wantTotal {
		t.Errorf("compared %d pinned configs, want %d", total, wantTotal)
	}
	if matched != wantTotal {
		t.Errorf("reproduced %d of %d pinned configs byte for byte", matched, wantTotal)
	}
	t.Logf("go-hamqtt reproduced %d of %d pinned discovery payloads across %d scenarios",
		matched, total, len(surfaceScenarios()))
}

// TestHamqttInputsReproduceThePublishedConfigTopics is what makes the proof
// above non-circular.
//
// buildHamqttInputs re-derives the discovery inputs from a warmed coordinator
// rather than intercepting them, because intercepting them would mean changing
// the publish path. A re-derivation that quietly differed from what pollOnce
// actually hands hass.Discovery.Publish would render a different entity set and
// the byte-equality above would be proving something smaller than it claims.
//
// So the same inputs are fed back through the DAEMON's own builders, into a
// recorder, and the resulting config plane must equal the golden's exactly.
func TestHamqttInputsReproduceThePublishedConfigTopics(t *testing.T) {
	for _, sc := range surfaceScenarios() {
		t.Run(sc.name, func(t *testing.T) {
			want := goldenConfigs(t, sc.name)
			in := buildHamqttInputs(t, sc)

			rec := &recorderMQTT{}
			cfg := scenarioConfig(sc)
			d := hass.New(cfg.HASSBaseTopic, cfg.MQTTTopic, cfg.Language, rec)
			if _, err := d.Publish(t.Context(), in.points, in.infos, in.climateInfos); err != nil {
				t.Fatalf("Publish: %v", err)
			}
			if len(in.schedules) > 0 {
				if _, err := d.PublishSchedules(t.Context(), in.schedules, in.configURL); err != nil {
					t.Fatalf("PublishSchedules: %v", err)
				}
			}

			got := map[string]string{}
			for _, m := range rec.snapshot() {
				if !isConfigTopic(m.Topic) {
					continue
				}
				b, err := json.Marshal(m.JSON)
				if err != nil {
					t.Fatal(err)
				}
				got[m.Topic] = string(b)
			}
			for _, topic := range sortedStringKeys(want) {
				if got[topic] != want[topic] {
					t.Errorf("re-derived inputs do not reproduce %s\n  golden %s\n  got    %s",
						topic, want[topic], got[topic])
				}
			}
			if len(got) != len(want) {
				t.Errorf("re-derived inputs produced %d configs, golden pins %d", len(got), len(want))
			}
		})
	}
}

